# Seeded random generator used by the randomized factoring step.

# SplitMix64: a small, fully specified generator, so that decompositions are
# reproducible across Julia versions.
mutable struct SplitMix64
    s::UInt64
end

function next!(r::SplitMix64)
    r.s += 0x9e3779b97f4a7c15
    z = r.s
    z = (z ⊻ (z >> 30)) * 0xbf58476d1ce4e5b9
    z = (z ⊻ (z >> 27)) * 0x94d049bb133111eb
    return z ⊻ (z >> 31)
end

# Uniform integer in [lo, hi].
function randint(r::SplitMix64, lo::Integer, hi::Integer)
    span = big(hi) - lo + 1
    x = big(0)
    for _ in 1:cld(ndigits(span; base=2) + 64, 64)
        x = (x << 64) | next!(r)
    end
    return lo + mod(x, span)
end
